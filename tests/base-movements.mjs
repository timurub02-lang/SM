import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {initBaseMovements,dailyBaseMovements} from '../lib/base-movements.ts';
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE clients(id TEXT PRIMARY KEY,data TEXT);CREATE TABLE settings(id TEXT PRIMARY KEY,data TEXT);');
const wrap=(sql,args=[])=>({bind:(...values)=>wrap(sql,values),run:async()=>db.prepare(sql).run(...args),first:async()=>db.prepare(sql).get(...args),all:async()=>({results:db.prepare(sql).all(...args)})});
const d={prepare:wrap,batch:async statements=>{db.exec('BEGIN');try{const r=[];for(const s of statements)r.push(await s.run());db.exec('COMMIT');return r;}catch(e){db.exec('ROLLBACK');throw e;}}};
await initBaseMovements(d);await initBaseMovements(d);
const put=(id,data)=>db.prepare('INSERT INTO clients VALUES(?,?)').run(id,JSON.stringify(data));
const change=(id,data)=>db.prepare('UPDATE clients SET data=? WHERE id=?').run(JSON.stringify(data),id);
put('c',{baseType:'M',source:'book.xlsx · ТК'});
change('c',{baseType:'M',sheet:'П'});
assert.equal(db.prepare('SELECT count(*) n FROM base_movements').get().n,0,'Equivalent sheet normalization is not a move');
change('c',{baseType:'M',sheet:'К'});
change('c',{baseType:'M',sheet:'К',name:'Changed name'});
assert.equal(db.prepare('SELECT count(*) n FROM base_movements').get().n,1);
change('c',{baseType:'J',sheet:'К'});
change('c',{baseType:'J',sheet:'П'});
const result=await dailyBaseMovements(d);
assert.equal(result.rows.length,3);
assert(result.rows.some(r=>r.fromBase==='M'&&r.toBase==='M'&&r.fromSheet==='П'&&r.toSheet==='К'&&r.total===1));
const before=db.prepare('SELECT count(*) n FROM base_movements').get().n;
db.exec('BEGIN');change('c',{baseType:'J',sheet:'ЧС'});db.exec('ROLLBACK');
assert.equal(db.prepare('SELECT count(*) n FROM base_movements').get().n,before,'Rollback removes the movement too');
db.prepare("UPDATE base_movements SET at='2026-10-28T21:00:00.000Z'").run();
assert.equal((await dailyBaseMovements(d,Date.parse('2026-10-29T10:00:00Z'))).rows.length,3);
assert.equal((await dailyBaseMovements(d,Date.parse('2026-10-28T20:00:00Z'))).rows.length,0);
db.close();console.log('Daily movements: normalized sheets, base changes, no-op updates, rollback and Moscow date passed');
