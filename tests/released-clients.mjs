import assert from 'node:assert/strict';
import {openDatabase} from '../server/sqlite.ts';
import {releasedClients,waitingRelease,releaseReadyDate,assignReleased} from '../lib/released-clients.ts';
import {applyRetention} from '../lib/crm.ts';
const now=new Date('2026-11-16T09:00:00Z'); // Monday; Friday release waits until Tuesday.
const c={id:'c',name:'Иванов Иван Иванович',baseType:'M',sheet:'П',owner:'',releasedAt:'2026-11-13T09:00:00Z',version:1};
assert(waitingRelease(c,now));assert.equal(releaseReadyDate(c),'2026-11-17');
assert(!waitingRelease(c,new Date('2026-11-16T21:00:00Z')));
for(const patch of [{owner:'op'},{releasedAt:'bad'},{releasedAt:'2026-11-17T09:00:00Z'},{sheet:'ЧС'},{sheet:'ПВ'},{sheet:'К'}])assert(!waitingRelease({...c,...patch},now));
const released=applyRetention({...c,owner:'old',sheet:'К',name:'Иванова Анна Ивановна',trialUntil:'2026-11-12T00:00:00Z'},[],now.getTime());
assert.equal(released.releasedFromOwner,'old');assert.equal(released.baseType,'J');assert.equal(released.sheet,'ж1');
const d=openDatabase(':memory:');
await d.prepare('CREATE TABLE clients(id TEXT PRIMARY KEY,data TEXT,version INTEGER)').run();
await d.prepare('CREATE TABLE employees(id TEXT PRIMARY KEY,data TEXT)').run();
await d.prepare('CREATE TABLE orders(id TEXT PRIMARY KEY,client_id TEXT,data TEXT)').run();
await d.prepare('CREATE TABLE events(id TEXT PRIMARY KEY,client_id TEXT,order_id TEXT,at TEXT,data TEXT)').run();
await d.prepare('CREATE TABLE base_dispatch_items(client_id TEXT,state TEXT)').run();
for(const [id,baseAccess] of [['op','M'],['jop','J']])await d.prepare('INSERT INTO employees VALUES(?,?)').bind(id,JSON.stringify({id,baseAccess,role:'operator',login:id})).run();
for(const id of ['c','reserved','active','stale','other'])await d.prepare('INSERT INTO clients VALUES(?,?,1)').bind(id,JSON.stringify({...c,id,baseType:id==='other'?'J':'M'})).run();
await d.prepare("INSERT INTO base_dispatch_items VALUES('reserved','pending')").run();
await d.prepare("INSERT INTO orders VALUES('o','active',?)").bind(JSON.stringify({status:'shipping'})).run();
assert.equal((await releasedClients(d,now)).length,5);
await assert.rejects(()=>assignReleased(d,'M','jop',[{id:'c',version:1}],'admin',now));
assert.deepEqual(await assignReleased(d,'M','op',['c','reserved','active','stale','other'].map(id=>({id,version:id==='stale'?0:1})),'admin',now),{assigned:1,skipped:4});
const assigned=JSON.parse((await d.prepare("SELECT data FROM clients WHERE id='c'").first()).data);
assert.equal(assigned.owner,'op');assert.equal(assigned.sheet,'К');assert.equal(assigned.trialReturnSheet,'П');
assert.equal((await d.prepare('SELECT count(*) n FROM events').first()).n,1);
assert.deepEqual(await assignReleased(d,'M','op',[{id:'c',version:1}],'admin',now),{assigned:0,skipped:1});
d.close();console.log('Released clients: Moscow workdays, routing, owner history, selected assignment, reservations, active orders, stale versions and repeat protected');
