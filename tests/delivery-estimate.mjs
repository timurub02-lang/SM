import assert from 'node:assert/strict';
import {deliveryEstimate} from '../lib/delivery-estimate.ts';
import {cdekStatusPatch} from '../lib/cdek-sync.ts';
const order={delivery:'cdek_pickup',status:'shipping',cdekTariff:{min:5,max:5},cdekAcceptedAt:'2026-11-11T10:00:00Z'};
assert.deepEqual(deliveryEstimate(order),{min:5,max:5,start:'2026-11-11',from:'2026-11-18',to:'2026-11-18'});
assert.deepEqual(deliveryEstimate({...order,cdekAcceptedAt:undefined}),{min:5,max:5});
assert.equal(deliveryEstimate({...order,cdekTariff:undefined}),null);
assert.equal(deliveryEstimate({...order,delivery:'russian_post'}),null);
assert.equal(deliveryEstimate({...order,cdekTariff:{min:6,max:5}}),null);
const holiday=deliveryEstimate({...order,cdekAcceptedAt:'2026-11-02T10:00:00Z',cdekTariff:{min:1,max:2}});
assert.equal(holiday.from,'2026-11-03');assert.equal(holiday.to,'2026-11-05');
assert.equal(deliveryEstimate({...order,cdekAcceptedAt:'2026-11-11T22:00:00Z'}).start,'2026-11-12');
assert.deepEqual(deliveryEstimate({...order,cdekAcceptedAt:'2030-01-01T00:00:00Z'}),{min:5,max:5,start:'2030-01-01'});
const entity={statuses:[{code:'CREATED',date_time:'2026-11-09T10:00:00Z'},{code:'RECEIVED_AT_SHIPMENT_WAREHOUSE',date_time:'2026-11-11T10:00:00Z'},{code:'RECEIVED_AT_SHIPMENT_WAREHOUSE',date_time:'2026-11-12T10:00:00Z'},{code:'RECEIVED_AT_SHIPMENT_WAREHOUSE',date_time:'2026-11-10T10:00:00Z',deleted:true}]};
const patch=cdekStatusPatch({status:'shipping'},entity,{},'');
assert.equal(patch.cdekAcceptedAt,'2026-11-11T10:00:00.000Z');
assert.equal(patch.cdekTransferredAt,'2026-11-09T10:00:00.000Z');
assert.equal(cdekStatusPatch({...order,...patch},entity,{},''),null);
assert.equal(cdekStatusPatch({status:'shipping'},{statuses:[entity.statuses[0]]},{},'').cdekAcceptedAt,undefined);
assert.equal(cdekStatusPatch({status:'shipping'},{...entity,is_return:true},{},''),null);
const {returnedFromCdek}=await import('../lib/cdek-shipment.ts');
assert.equal(returnedFromCdek(order,'2026-11-12T10:00:00Z').cdekAcceptedAt,undefined);
console.log('Delivery estimate: actual acceptance, working days, holidays, Moscow date, missing quote/calendar, duplicate and return protection passed');
