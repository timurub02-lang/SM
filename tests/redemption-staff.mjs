import assert from 'node:assert/strict';
import {employeeForManager,canCreateRedemptionStaff,teamEmployees,needsDepartment} from '../lib/crm.ts';
import {authorizeCrm,visibleState} from '../lib/permissions.ts';
const actor={id:'r',role:'redemption',canCreateRedemptionStaff:true,name:'Lead',login:'lead',alias:'',skLogin:'',salary:0,bonus:0,version:1};
const normal={...actor,id:'other',canCreateRedemptionStaff:undefined};
const admin={...actor,id:'admin',role:'admin'};
const state={employees:[actor,normal,admin],orders:[],clients:[],events:[],settings:{retentionDays:30}};
const data={name:'New staff',login:'new',alias:'',skLogin:'',role:'admin',department:'1',salary:0,bonus:0,canCreateRedemptionStaff:true};
assert(canCreateRedemptionStaff(actor));assert(!canCreateRedemptionStaff(normal));
assert.equal(needsDepartment('redemption'),false);
const result=employeeForManager(actor,data);
assert.equal(result.role,'redemption');assert.equal(result.department,undefined);assert.equal(result.canCreateRedemptionStaff,undefined);
assert.throws(()=>employeeForManager(normal,data));
assert.throws(()=>employeeForManager(actor,data,normal));
assert.doesNotThrow(()=>authorizeCrm(actor,{action:'saveEmployee',employee:data},state));
for(const request of [{action:'saveEmployee',id:'admin',employee:data},{action:'deleteEmployee',id:'other'}])assert.throws(()=>authorizeCrm(actor,request,state));
assert.throws(()=>authorizeCrm(normal,{action:'saveEmployee',employee:data},state));
assert.deepEqual(teamEmployees(state.employees,actor).map(e=>e.id),['r','other']);
assert.deepEqual(visibleState(state,actor).employees.map(e=>e.id),['r','other']);
console.log('Scoped redemption staff creation passed');
