import assert from 'node:assert/strict';
import {basketAmount,isBasketTotal,withBasketTotal} from '../lib/basket-total.ts';
import {itemsSchema,total} from '../lib/crm.ts';
import {shipmentPayload,shipmentFormSchema} from '../lib/cdek-shipment.ts';
const old=[{name:'Товар',quantity:3,price:100},{name:'ИТОГО',quantity:1,price:4700}];
const next=withBasketTotal(old,5000.01);
assert.deepEqual(next,[{name:'Товар',quantity:3,price:0},{name:'ИТОГО',quantity:1,price:5000.01}]);
assert.equal(basketAmount(old),5000);assert.equal(basketAmount(next),5000.01);assert.equal(total({items:next}),5000.01);
assert.equal(isBasketTotal({name:' итого '}),true);
const added=withBasketTotal([...next,{name:'Ещё товар',quantity:7,price:0}],basketAmount(next));
assert.equal(added.at(-1).name,'ИТОГО');assert.equal(basketAmount(added),5000.01);assert.equal(added.filter(isBasketTotal).length,1);
assert.equal(basketAmount(withBasketTotal([{name:'Товар',quantity:8,price:0}],5000.01)),5000.01);
assert(itemsSchema.safeParse(next).success);assert(itemsSchema.safeParse(old).success);
for(const items of [[{name:'Товар',quantity:1,price:0}],withBasketTotal([],100),withBasketTotal(old,0),withBasketTotal(old,-1),[...next,next.at(-1)]])assert(!itemsSchema.safeParse(items).success);
const order={id:'test',status:'packing',delivery:'cdek_pickup',items:next,cdekTariff:{code:136,params:{delivery:'cdek_pickup',originMode:'warehouse',weight:.875,length:25,width:5,height:35,originPostalCode:'109388'}}};
const products=next.map((item,i)=>({name:item.name,sku:'P'+i,weight:1,cost:1}));
const form=shipmentFormSchema.parse({shipmentPoint:'MSK',deliveryPoint:'TEST',payment:'cod',deliveryCost:0});
const payload=shipmentPayload(order,{name:'Test',phone:'+79990000001'},products,form);
assert.equal(payload.packages[0].items.reduce((sum,item)=>sum+Math.round(item.payment.value*100)*item.amount,0),500001);
assert.equal(payload.packages[0].items[0].amount,3);
console.log('Basket total: legacy sums, quantities, bottom total, validation and exact CDEK payment passed');
