import assert from 'node:assert/strict';
import {openDatabase} from '../server/sqlite.ts';
import {cashSchema} from '../lib/cash.ts';
import {initCashNotifications,acknowledgeCashNotice} from '../lib/cash-notifications.ts';
import {maintainReminders} from '../lib/reminder-maintenance.ts';
import {notificationPopupTab,notificationSections} from '../lib/notification-sections.ts';
const d=openDatabase(':memory:');
await d.prepare('CREATE TABLE employees(id TEXT PRIMARY KEY,data TEXT)').run();
for(const e of [{id:'admin',role:'admin',name:'Admin'},{id:'admin2',role:'admin',name:'Admin2'},{id:'head',role:'department_head',name:'Head'}])await d.prepare('INSERT INTO employees VALUES(?,?)').bind(e.id,JSON.stringify(e)).run();
await d.batch(cashSchema.map(sql=>d.prepare(sql)));
const add=(id,kind='add',recipient='head')=>d.prepare('INSERT OR IGNORE INTO cash_operations(id,kind,sender,recipient,amount,purpose,date,created_at,accepted_at,actor,sender_name,recipient_name) VALUES(?,?,?,?,?,?,?,?,?,?,?,?)').bind(id,kind,kind==='transfer'?'admin':null,recipient,12345,'Test','2026-11-16','2026-11-16T10:00:00Z',kind==='transfer'?null:'2026-11-16T10:00:00Z','head',kind==='transfer'?'Admin':'','Head').run();
await add('old');await initCashNotifications(d);await initCashNotifications(d);
assert.equal((await d.prepare('SELECT * FROM reminders').all()).results.length,0,'No historical backfill');
await add('new');await add('new');
let rows=(await d.prepare('SELECT * FROM reminders').all()).results;
assert.equal(rows.length,2,'One notice per admin, idempotent operation');
assert.ok(rows.every(r=>r.employee_id.startsWith('admin')));
assert.match(JSON.parse(rows[0].data).text,/Head.*123.45.*Test/);
await d.prepare("UPDATE reminders SET read_at='2026-11-16T10:01:00Z' WHERE employee_id='admin'").run();
const events=async id=>(await d.prepare('SELECT data FROM reminders WHERE employee_id=?').bind(id).all()).results.map(r=>JSON.parse(r.data));
assert.equal(notificationPopupTab(await events('admin'),[]),'acknowledge');
assert.equal(notificationSections([],await events('admin')).tasks.length,1,'Opening is not acknowledgement');
await assert.rejects(acknowledgeCashNotice(d,{id:'head',role:'department_head'},'cash:new:created','2026-11-16T10:02:00Z'));
await assert.rejects(acknowledgeCashNotice(d,{id:'admin',role:'admin'},'cash:missing:created','2026-11-16T10:02:00Z'));
await acknowledgeCashNotice(d,{id:'admin',role:'admin'},'cash:new:created','2026-11-16T10:02:00Z');
assert.equal(notificationSections([],await events('admin')).tasks.length,0);
assert.equal(notificationSections([],await events('admin2')).tasks.length,1,'Personal acknowledgement');
assert.equal(notificationSections([],await events('admin')).events.length,0,'Acknowledged notice stays out of bell');
await add('transfer','transfer');
await d.prepare("UPDATE cash_operations SET accepted_at='2026-11-16T10:03:00Z' WHERE id='transfer'").run();
assert.equal((await events('admin')).filter(r=>r.id.startsWith('cash:transfer:')).length,2,'Transfer created and received are distinct');
await d.prepare("UPDATE cash_operations SET accepted_at=accepted_at WHERE id='transfer'").run();
assert.equal((await events('admin')).filter(r=>r.id.startsWith('cash:transfer:')).length,2);
for(let i=0;i<25;i++)await add('more'+i);
await maintainReminders(d,{employees:[{id:'admin',role:'admin'}],orders:[],clients:[],settings:{}});
assert.equal((await events('admin')).filter(r=>!r.acknowledgedAt).length,27,'Unacknowledged cash notices survive history pruning');
assert.equal((await d.prepare("SELECT balance FROM cash_balances WHERE employee='head'").first()).balance,28*12345,'Acknowledgement never alters money');
console.log('Cash notices: atomic insert/accept, no backfill/duplicates, personal admin-only acknowledgement, pruning and money unchanged passed');
