import assert from 'node:assert/strict';
import {clientRetentionPreview as preview} from '../lib/client-retention-preview.ts';
import {initialBaseSettings} from '../lib/base-policy.ts';
const now=Date.parse('2026-11-11T12:00:00Z'),config=initialBaseSettings();
config.retention.operators.op={mode:'fixed',days:14,defaultWeeks:2,bands:[]};
const c={id:'c',name:'Иванов Иван Иванович',owner:'op',sheet:'К',assignedUntil:'',assignmentStartedAt:'2026-10-01T00:00:00Z',importRetentionUntil:'2027-01-01T00:00:00Z'};
const o={id:'o',clientId:'c',manager:'op',status:'redeemed',createdAt:'2026-10-10T00:00:00Z',redeemedAt:'2026-11-01T12:00:00Z'};
const original=JSON.stringify({c,o,config});
assert.deepEqual(preview([c],[o],config,now),{c:{until:'2026-11-15T12:00:00.000Z'}});
assert.equal(JSON.stringify({c,o,config}),original,'Preview must not mutate client, order or settings');
assert.deepEqual(preview([c],[{...o,redeemedAt:'2026-10-01T00:00:00Z'}],config,now),{c:{expiresAfterPremium:true}});
assert.deepEqual(preview([{...c,retentionExtensionUntil:'2026-11-20T00:00:00Z'}],[o],config,now),{c:{until:'2026-11-20T00:00:00.000Z'}});
assert.deepEqual(preview([c],[o,{...o,id:'active',status:'shipping'}],config,now),{});
assert.deepEqual(preview([c],[{...o,premiumStage:{status:'paid',periodId:'paid'}}],config,now),{});
assert.deepEqual(preview([c],[{...o,redeemedAt:undefined}],config,now),{c:{}});
assert.deepEqual(preview([c],[{...o,manager:'old'}],config,now),{});
assert.deepEqual(preview([],[o],config,now),{});
config.retention.operators.op.days=35;
assert.deepEqual(preview([c],[o],config,now),{c:{until:'2026-12-06T12:00:00.000Z'}});
console.log('Retention preview: 2/5 weeks, expired, extension, active/paid orders, unknown dates, visibility and no mutation passed');
