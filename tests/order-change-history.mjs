import assert from 'node:assert/strict';
import {orderChangeHistory,withOrderChanges} from '../lib/order-change-history.ts';
const before={id:'o',address:'Старый адрес',addressParts:{postalCode:'111111',flat:'1'},items:[{name:'Товар',quantity:2,price:100}],status:'draft',manager:'op',logisticComment:'старый',version:1,updatedAt:'2026-11-16T00:00:00Z'};
const after={...before,address:'Новый адрес',addressParts:{flat:'2',postalCode:'111111'},items:[{name:'Товар',quantity:3,price:120},{name:'Добавлен',quantity:1,price:0}],status:'confirm',manager:'head',logisticComment:'',version:2,updatedAt:'2026-11-16T01:00:00Z',_mutation:'private',delivery:'russian_post'};
const text=withOrderChanges('Сохранено',before,after,[{id:'op',name:'Оператор'},{id:'head',name:'Руководитель'}]);
assert.match(text,/Адрес: Старый адрес → Новый адрес/);
assert.match(text,/Квартира: 1.*→.*Квартира: 2/);
assert.match(text,/Корзина: Товар: 2 шт. × 100 ₽ → Товар: 3 шт. × 120 ₽; Добавлен: 1 шт. × 0 ₽/);
assert.match(text,/Статус: Оформление → Подтверждение/);
assert.match(text,/Оператор: Оператор → Руководитель/);
assert.match(text,/Комментарий логиста: старый → не указано/);
assert.match(text,/Способ доставки: не указано → Почта России/);
assert.doesNotMatch(text,/version|updatedAt|mutation|private/);
assert.deepEqual(orderChangeHistory(before,{...before,version:2,updatedAt:'other',addressParts:{flat:'1',postalCode:'111111'}}),[]);
assert.match(withOrderChanges('Удалено',after,{...after,items:[]}),/ → пусто/);
assert.match(withOrderChanges('ПВЗ',before,{...before,cdekTariff:{deliveryPoint:{code:'MSK1',address:'Пункт'}}}),/ПВЗ: Код: MSK1; Адрес: Пункт/);
assert.match(withOrderChanges('Перезвон',before,{...before,due:'2026-11-17T06:00:00.000Z'}),/17.11.2026, 09:00:00 МСК/);
console.log('History: actual before/after, basket additions/removal, address fields, comments, roles, time zone and unchanged values passed');
const {visibleOrderHistoryText}=await import('../lib/order-change-history.ts');
const privateText='Оплата принята\nПриём оплаты: не указано → Логин оператора: secret\nКомментарий оператора: +79991234567';
assert.match(visibleOrderHistoryText(privateText,'admin'),/secret/);
assert.doesNotMatch(visibleOrderHistoryText(privateText,'operator'),/secret|79991234567/);
assert.match(visibleOrderHistoryText(privateText,'operator'),/\[телефон\]/);
