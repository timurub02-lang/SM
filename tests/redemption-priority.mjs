import assert from 'node:assert/strict';
import {eligibleForRedemption,compareRedemptionPriority} from '../lib/redemption-priority.ts';
const statuses=['ACCEPTED_AT_PICK_UP_POINT','NOT_DELIVERED'];
const order=(id,code,delivery='cdek_courier')=>({id,delivery,cdekStatus:code?{code}:undefined});
const waiting=order('waiting','CREATED'),ready=order('ready','NOT_DELIVERED'),pickup=order('pickup','ACCEPTED_AT_PICK_UP_POINT'),unknown=order('unknown'),post=order('post','NOT_DELIVERED','russian_post');
assert.equal(eligibleForRedemption(ready,statuses),true);
assert.equal(eligibleForRedemption(waiting,statuses),false);
assert.equal(eligibleForRedemption(unknown,statuses),false);
assert.equal(eligibleForRedemption(post,statuses),false);
assert.equal(eligibleForRedemption(ready,[]),false);
assert.deepEqual([waiting,ready,unknown,pickup,post].sort((a,b)=>compareRedemptionPriority(a,b,statuses)).map(o=>o.id),['ready','pickup','waiting','unknown','post']);
assert.deepEqual([waiting,ready].sort((a,b)=>compareRedemptionPriority(a,b,['CREATED'])).map(o=>o.id),['waiting','ready']);
console.log('Redemption priority: configured statuses, stable groups, missing status, carrier and settings changes passed');
assert.deepEqual([ready,waiting,pickup].sort((a,b)=>compareRedemptionPriority(a,b,statuses,new Set(['ready','waiting']))).map(o=>o.id),['pickup','ready','waiting']);
const {summarizeRedemption,readRedemptionSummaries}=await import('../lib/redemption-summary.ts');
const now=new Date('2026-10-27T21:01:00Z');
assert.equal(summarizeRedemption({days:{'2026-10-27':{at:'2026-10-27T10:00:00Z'}}},now).workedToday,false);
assert.equal(summarizeRedemption({days:{'2026-10-28':{at:'2026-10-27T21:00:00Z'}}},now).workedToday,true);
const preserved=summarizeRedemption({result:'date',resultDate:'2026-10-30',author:'Buyer',lastDay:'2026-10-26',days:{'2026-10-26':{at:'2026-10-26T10:00:00Z'}},lastAttempt:{at:'2026-10-27T21:00:00Z'}},now);
assert.equal(preserved.workedToday,true);assert.equal(preserved.date,'2026-10-30');assert.equal(preserved.author,'Buyer');assert.equal(preserved.at,'2026-10-26T10:00:00Z');
const {openDatabase}=await import('../server/sqlite.ts');const d=openDatabase(':memory:');
await d.prepare('CREATE TABLE orders(id TEXT PRIMARY KEY,data TEXT)').run();
await d.prepare('CREATE TABLE settings(id TEXT PRIMARY KEY,data TEXT)').run();
await readRedemptionSummaries(d,[]);
await d.prepare("INSERT INTO orders(id) VALUES('visible'),('hidden')").run();
for(const id of ['visible','hidden'])await d.prepare('INSERT INTO redemption_entries(order_id,entered_at,data) VALUES(?,?,?)').bind(id,now.toISOString(),JSON.stringify({result:'courier',days:{'2026-10-28':{at:now.toISOString()}}})).run();
assert.deepEqual(Object.keys(await readRedemptionSummaries(d,['visible'],now)),['visible']);d.close();
console.log('Three groups, Moscow day, preserved future result after ND and visible-order scope passed');

assert.equal(summarizeRedemption({result:'none',days:{}},now).result,'');

const pending=new Set(['ready','waiting']);
assert.deepEqual([pickup,ready,unknown,waiting,post].sort((a,b)=>compareRedemptionPriority(a,b,statuses,new Set(['ready']),pending)).map(o=>o.id),['ready','waiting','pickup','unknown','post']);
assert.deepEqual([pickup,ready,waiting].sort((a,b)=>compareRedemptionPriority(a,b,statuses,new Set(['ready']),new Set())).map(o=>o.id),['pickup','ready','waiting']);
console.log('Pending operator decisions first, including worked/ineligible orders; resolved decisions restore normal priority');
