import assert from 'node:assert/strict';
import {NavigationRefresh,preserveRefreshForm} from '../lib/navigation-refresh.ts';
const gate=new NavigationRefresh();
const update=(view,overlayOpen=false,blocked=false)=>gate.update({view,overlayOpen,blocked});
assert.equal(update('mine'),false,'initial fetch is already owned by mount');
assert.equal(update('orders'),true,'entering orders refreshes without waiting for the timer');
assert.equal(update('orders'),false,'rerenders do not cause more GETs');
assert.equal(update('orders',true),false,'opening a form must not reload it');
assert.equal(update('orders',false),true,'closing a card refreshes immediately');
assert.equal(update('orders',true),false);
assert.equal(update('orders',false,true),false,'do not read during a write');
assert.equal(update('orders',false,false),true,'a close during a write is not lost');
assert.equal(update('orders'),false);
assert.equal(update('mine',true),false,'navigation while a form is open waits');
assert.equal(update('shipping',true),false);
assert.equal(update('shipping'),true,'coalesce intermediate navigation');
assert.equal(update('mine',false,true),false,'offline/hidden navigation queues');
assert.equal(update('mine'),true);
assert.equal(preserveRefreshForm(true,true),true,'background GET keeps unsaved form data');
assert.equal(preserveRefreshForm(true,false),false,'a GET begun with a form open applies fully after close');
assert.equal(preserveRefreshForm(false,true),false,'explicit refresh after a mutation still applies');
console.log('PASS: immediate navigation/close refresh, coalescing, writes, and response-time form protection');
