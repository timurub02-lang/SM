import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openDatabase} from '../server/sqlite.ts';
import {receiveSkOrderEvent,initSkOrderEvents} from '../lib/sk-order-events.ts';
const folder=mkdtempSync(join(tmpdir(),'crm-sk-batches-')),path=join(folder,'test.sqlite'),secret='synthetic-provider-secret-'.repeat(2);
const d=openDatabase(path),other=openDatabase(path);
const event=id=>({type:'call_result',call:{id},call_result:{result_id:47,comment:'original'}});
const request=(payload,key='batch-key')=>new Request('https://fixture.invalid/api/sk-order-events',{method:'POST',headers:{Authorization:'Bearer '+secret,'Content-Type':'application/json; charset=utf-8','Idempotency-Key':key},body:JSON.stringify(payload)});
const receive=(payload,key,db=d)=>receiveSkOrderEvent(db,request(payload,key),secret);
const count=()=>d.prepare('SELECT COUNT(*) n FROM sk_order_events').first('n');
try{
 await d.prepare('CREATE TABLE settings(id TEXT PRIMARY KEY,data TEXT NOT NULL)').run();
 await d.prepare('INSERT INTO settings VALUES(?,?)').bind('sk-order-import',JSON.stringify({enabled:true,resultIds:[47]})).run();
 await initSkOrderEvents(d);
 const ignored={...event(99),call_result:{result_id:99}};
 assert.equal((await receive([event(1),event(2),ignored,{type:'form_response'},{type:'call_project_case_failed'}])).status,200);
 assert.equal(await count(),2);
 assert.equal((await receive([event(2),event(1)])).status,200,'reordered retry');assert.equal(await count(),2);
 assert.equal((await receive([event(1),{...event(1),call_result:{result_id:47,comment:'changed'}}],'new-key')).status,200);
 assert.equal(await d.prepare("SELECT comment FROM sk_order_events WHERE call_id='1'").first('comment'),'original');
 assert.equal((await receive(event(3),'legacy-single')).status,200);
 assert.equal((await receive(event(3),'legacy-single')).status,200);
 assert.equal((await receive(event(4),'legacy-single')).status,409,'single key conflict stays rejected');
 assert.equal((await receive([event(3)],'legacy-single')).status,200,'single to batch retry');
 assert.equal((await receive({...event(4),call:{id:4,result_id:99}},'final-result')).status,200,'final result is authoritative');
 assert.equal(await d.prepare("SELECT result_id FROM sk_order_events WHERE call_id='4'").first('result_id'),'47');
 assert.equal((await receive({...event(5),custom_fields:{unused:'x'.repeat(70000)},call_result:{result_id:'47',comment:'a'.repeat(70000)}},'large-fields')).status,200);
 assert.equal(await d.prepare("SELECT length(comment) n FROM sk_order_events WHERE call_id='5'").first('n'),3000);
 const fifty=Array.from({length:50},(_,n)=>({...event(5000+n),lead:{comment:'x'.repeat(2000)}}));
 assert.equal((await receive(fifty,'provider-fifty')).status,200,'ordinary fifty-event provider batch exceeds the former 64 KiB limit');
 assert.equal((await receive(fifty,'provider-fifty')).status,200);assert.equal(await count(),55);
 const before=await count();
 assert.equal((await receive([event(6),{...event(7),call:{id:null}}],'invalid-batch')).status,400);assert.equal(await count(),before);
 assert.equal((await receive({type:'unknown'},'unknown')).status,400);
 assert.equal((await receive([],'empty')).status,200);assert.equal((await receive({type:'form_response'},'form')).status,200);
 await d.prepare("CREATE TRIGGER fail_second BEFORE INSERT ON sk_order_events WHEN NEW.call_id='42' BEGIN SELECT RAISE(ABORT,'synthetic write failure'); END").run();
 await assert.rejects(receive([event(41),event(42)],'write-failure'),/synthetic write failure/);
 assert.equal(await count(),before,'a failed write rolls back the first batch row too');
 await d.prepare('DROP TRIGGER fail_second').run();
 await d.prepare('DELETE FROM sk_order_events').run();
 await d.prepare("WITH RECURSIVE n(x) AS (SELECT 1 UNION ALL SELECT x+1 FROM n WHERE x<9999) INSERT INTO sk_order_events(call_id,event_key,result_id,comment,received_at) SELECT 'full-'||x,'full-'||x,'47','',0 FROM n").run();
 const full=await receive([event(51),event(52)],'capacity');assert.equal(full.status,503);assert.equal(full.headers.get('Retry-After'),'60');
 assert.equal(await count(),9999,'one free slot does not partially admit two calls');
 await d.prepare("DELETE FROM sk_order_events WHERE call_id='full-1'").run();
 assert.equal((await receive([event(51),event(52)],'capacity')).status,200);assert.equal(await count(),10000);
 assert.equal((await receive([event(52),event(51)],'capacity')).status,200,'full queue still acknowledges existing calls');
 await d.prepare("DELETE FROM sk_order_events WHERE call_id IN ('full-2','full-3','full-4')").run();
 const concurrent=await Promise.all([receive([event(61),event(62)],'parallel-one'),receive([event(63),event(64)],'parallel-two',other)]);
 assert.deepEqual(concurrent.map(r=>r.status).sort(),[200,503]);assert.equal(await count(),9999,'concurrent batches cannot exceed capacity or partially persist');
 console.log('SK webhook batches: single/batch/mixed events, final result, large fields, replay, legacy keys, validation, write rollback, capacity and concurrent admission passed');
}finally{d.close();other.close();rmSync(folder,{recursive:true,force:true});}
