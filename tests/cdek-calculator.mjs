import assert from 'node:assert/strict';
import {calculationSchema,calculationPayload,tariffMode,canManageDelivery} from '../lib/cdek-calculator.ts';
const input={actorId:'denis',orderId:'one',slot:1,delivery:'cdek_pickup',originPostalCode:'101000',originMode:'warehouse',weight:1.25,length:20,width:15,height:10};
const p=calculationSchema.parse(input);
assert.equal(calculationPayload(p,'350063').packages[0].weight,875);
assert.equal(calculationPayload(p,'350063').currency,1);
assert.equal(tariffMode(p),4);
assert.equal(tariffMode({...p,delivery:'cdek_courier'}),3);
assert.equal(tariffMode({...p,originMode:'door'}),2);
assert.throws(()=>calculationPayload(p,''));
assert.throws(()=>calculationSchema.parse({...p,weight:0}));
assert(!canManageDelivery('operator','draft'));
assert(canManageDelivery('admin','packing'));
assert(!canManageDelivery('admin','shipping'));
assert(canManageDelivery('logistic','packing'));
assert(!canManageDelivery('logistic','shipping'));
console.log('Delivery calculator checks passed');
const {calculationError}=await import('../lib/cdek-calculator.ts');
assert.match(calculationError(400,[{code:'v2_sender_location_not_recognized'}]),/индекс отправления/);
assert.match(calculationError(429),/слишком много/);
assert(!calculationError(400,[{code:'<private detail>'}]).includes('private'));

for(const role of ['admin','logistic','chief_logistic'])for(const status of ['confirm','extra'])assert(canManageDelivery(role,status));
for(const status of ['confirm','extra'])assert(!canManageDelivery('operator',status));

const {confirmSavedTariff}=await import('../lib/cdek-calculator.ts');
const {packingStage}=await import('../lib/crm.ts');
const pending={status:'packing',delivery:'cdek_courier',cdekTariff:{code:137,amount:450,needsConfirmation:true,params:{delivery:'cdek_courier',weight:.875}}};
assert.equal(packingStage(pending),'new');
const confirmed=confirmSavedTariff(pending);
assert.equal(confirmed.amount,450);
assert.equal(confirmed.code,137);
assert.equal(confirmed.needsConfirmation,false);
assert.equal(pending.cdekTariff.needsConfirmation,true);
assert.equal(packingStage({...pending,cdekTariff:confirmed}),'calculated');
for(const patch of [{status:'confirm'},{status:'shipping'},{delivery:'cdek_pickup'},{cdekTariff:undefined},{cdekTariff:{...pending.cdekTariff,params:{delivery:'cdek_courier',weight:1}}}])assert.throws(()=>confirmSavedTariff({...pending,...patch}));
console.log('Saved tariff confirmation and packing stages passed');
