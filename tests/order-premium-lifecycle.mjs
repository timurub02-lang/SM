import assert from 'node:assert/strict';
import {applyPremiumStages,freezePeriod,signPeriod,payPeriod} from '../lib/premium-ledger.ts';
import {orderDisplayGroup} from '../lib/order-premium-stage.ts';
import {mayCallEndpoint} from '../lib/permissions.ts';
import {orderGroup,closedOrderCallBlocked} from '../lib/crm.ts';
const op={id:'op',role:'operator',department:'a',bonus:10};
const head={id:'head',name:'Head A',role:'department_head',department:'a',leaderPremium:{model:'salary_bonus',fixedPerPeriod:0,links:[]}};
const head2={...head,id:'head2',name:'Head B',department:'b'};
const staff=[op,head,head2];
const endpoint=new URL('https://example.test/api/premium/lifecycle');
assert.equal(mayCallEndpoint(op,endpoint,'POST',{}),false);
assert.equal(mayCallEndpoint(head,endpoint,'POST',{}),true);
assert.equal(mayCallEndpoint({id:'admin',role:'admin'},endpoint,'POST',{}),true);
const receipt=(id,date)=>({id,manager:'op',status:'redeemed',delivery:'cdek_pickup',comments:[{text:'History retained'}],cdekRemittances:[{registry:id,paymentDate:date,amountCents:90000,collectedCents:100000}]});
const initial=receipt('initial','2026-10-25'),next=receipt('next','2026-10-28'),late=receipt('late','2026-10-25');
let ledger={revision:'1',activePeriod:'2026-10-2',initialPeriod:'2026-10-2',historyReconciled:true,periods:{'2026-10-2':{status:'open',signatures:{}}}};
const post={...initial,id:'post',delivery:'russian_post',cdekRemittances:undefined,paymentReceivedAt:'2026-10-25T10:00:00Z',paymentReceivedAmount:1000};
const courier={...post,id:'courier',delivery:'moscow_courier'};
const groups=(l,orders)=>Object.fromEntries(applyPremiumStages(l,orders,staff).map(o=>[o.id,orderDisplayGroup(o).id]));
assert.deepEqual(groups(ledger,[post,courier,{...post,id:'unreceived',paymentReceivedAt:undefined}]),{post:'accrued',courier:'accrued',unreceived:'paid'});
assert.deepEqual(groups(ledger,[initial,next]),{initial:'accrued',next:'paid'});
ledger=freezePeriod(ledger,'2026-10-2',[initial,next],staff,{},'admin','2026-10-29T10:00:00Z');
assert.deepEqual(groups(ledger,[initial,next,late]),{initial:'accrued',next:'paid',late:'paid'});
assert.throws(()=>payPeriod(ledger,'2026-10-2','admin','now'),/руководители/);
assert.throws(()=>signPeriod(ledger,'2026-10-2',op,'now'),/недоступно/);
ledger=signPeriod(ledger,'2026-10-2',head,'now');
assert.throws(()=>payPeriod(ledger,'2026-10-2','admin','now'),/руководители/);
ledger=signPeriod(ledger,'2026-10-2',head2,'now');
const snapshot=JSON.stringify(ledger.periods['2026-10-2'].orders);
ledger=payPeriod(ledger,'2026-10-2','admin','now');
assert.equal(ledger.activePeriod,'2026-11-1');
assert.deepEqual(groups(ledger,[initial,next,late]),{initial:'premium_paid',next:'accrued',late:'accrued'});
assert.equal(JSON.stringify(ledger.periods['2026-10-2'].orders),snapshot);
assert.throws(()=>payPeriod(ledger,'2026-10-2','admin','now'));
for(const o of applyPremiumStages(ledger,[initial,next,late],staff)){
 assert.equal(o.status,'redeemed');
 assert.equal(orderGroup(o).id,'paid');
 assert.equal(o.comments[0].text,'History retained');
 assert.equal(closedOrderCallBlocked(op,o,{owner:''}),true);
}
assert.equal(initial.premiumStage,undefined);
console.log('Order stages: all heads required, frozen membership, late receipt rollover, history and call restrictions passed');

const excelReceipt={periodId:'2026-10-2',source:'Synthetic worksheet',sha256:'fixture',amount:1000,recordedAt:'2026-10-29T12:00:00Z'};
const excelOrder={...initial,id:'excel',legacyLv:{orderId:'123'},cdekRemittances:[],importedPayment:excelReceipt};
const imported={revision:'import',activePeriod:'2026-10-2',initialPeriod:'2026-10-2',periods:{'2026-10-2':{status:'open',signatures:{},source:{name:'fixture',sha256:'fixture',importedAt:'now'},rows:[],orders:[{id:'excel',externalId:'123',employeeId:op.id,login:op.login,department:'1',amount:1000}]}}};
assert.equal(groups(imported,[excelOrder]).excel,'accrued');
assert.equal(excelOrder.cdekRemittances.length,0,'Import must not manufacture a CDEK registry');
const {packingStage,canReceivePayment}=await import('../lib/crm.ts');
const importedPost={...post,paymentReceivedAt:undefined,importedPayment:excelReceipt};
assert.equal(packingStage(importedPost),'payment_received');
assert.equal(canReceivePayment(importedPost,'chief_logistic'),false,'Imported receipt must not be received into cash twice');
console.log('Excel receipt evidence: accrued projection and logistic acceptance without duplicate receipt passed');
