import assert from 'node:assert/strict';
import {openDatabase} from '../server/sqlite.ts';
import {changeClientReminder,personalClientReminders,clientReminderTasks,canRemindClient} from '../lib/client-reminders.ts';
import {authorizeCrm} from '../lib/permissions.ts';
const d=openDatabase(':memory:');await d.prepare('CREATE TABLE clients(id TEXT PRIMARY KEY)').run();await d.prepare("INSERT INTO clients VALUES('c')").run();
const e={id:'op',role:'operator'},other={id:'other',role:'operator'},c={id:'c',name:'Клиент',owner:e.id};
const s={clients:[c],employees:[e,other],orders:[],events:[],settings:{}};
const now='2026-10-21T13:00:00.000Z',due='2026-10-26T07:00:00.000Z';
const p={action:'createClientReminder',clientId:'c',reminderId:crypto.randomUUID(),due,text:'Позвонить через 5 дней'};
assert.equal(canRemindClient(s,e,'c'),true);assert.equal(canRemindClient(s,other,'c'),false);
assert.doesNotThrow(()=>authorizeCrm(e,p,s));assert.throws(()=>authorizeCrm(other,p,s));
await assert.rejects(changeClientReminder(d,s,other,p,now),/доступа/);
await assert.rejects(changeClientReminder(d,s,e,{...p,due:now},now),/будущее/);
await assert.rejects(changeClientReminder(d,s,e,{...p,text:' '},now));
await changeClientReminder(d,s,e,p,now);await changeClientReminder(d,s,e,p,now);
let rows=await personalClientReminders(d,s,e);assert.equal(rows.length,1);
assert.equal(clientReminderTasks(rows,s,Date.parse(due)-1).length,0);
const tasks=clientReminderTasks(rows,s,Date.parse(due));assert.equal(tasks.length,1);assert.equal(tasks[0].clientId,'c');assert.equal(tasks[0].orderId,undefined);
assert.equal((await personalClientReminders(d,s,{id:'admin',role:'admin'})).length,0);
assert.equal((await personalClientReminders(d,{...s,clients:[{...c,owner:other.id}]},e)).length,0);
await assert.rejects(changeClientReminder(d,s,other,{...p,action:'closeClientReminder',resolution:'done'},due));
await changeClientReminder(d,s,e,{...p,action:'closeClientReminder',resolution:'done'},due);
assert.equal((await personalClientReminders(d,s,e)).length,0);
assert.equal(c.owner,e.id);assert.equal(s.orders.length,0);
console.log('Personal client reminders: due times, idempotency, isolation, access and completion passed');
